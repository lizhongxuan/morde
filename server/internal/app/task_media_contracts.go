package app

import (
	"context"
	"io"
	"time"
)

// TaskMediaPreview is a server-staged result awaiting the Task owner's save decision.
// The preview is never a provider URL and is not available after the decision expires.
type TaskMediaPreview struct {
	Body      io.ReadCloser
	MediaType string
	SizeBytes int64
}

type TaskMediaStagedObjectState string

const (
	TaskMediaPreviewPending TaskMediaStagedObjectState = "preview"
	TaskMediaPreviewSaving  TaskMediaStagedObjectState = "saving"
	TaskMediaPreviewSaved   TaskMediaStagedObjectState = "published"
	TaskMediaPreviewDiscard TaskMediaStagedObjectState = "discarded"
	TaskMediaPreviewExpired TaskMediaStagedObjectState = "expired"
)

type TaskMediaCleanupState string

const (
	TaskMediaCleanupPending  TaskMediaCleanupState = "pending"
	TaskMediaCleanupComplete TaskMediaCleanupState = "complete"
)

// TaskMediaStagedObject joins Task operation and Token ledger state with the
// staged bytes metadata; operation and usage state remain canonical in their
// existing ledgers.
type TaskMediaStagedObject struct {
	// OwnerID is the Task/Workspace owner; InitiatorID is the account whose
	// model-call ledger pays for Project Tasks.
	TaskID, OwnerID, InitiatorID, OperationID, RuntimeCallID string
	OperationKey, ProviderOperationID                        string
	RequestHash                                              []byte
	OperationStatus, TokenState                              string
	ReservedTokens                                           int64
	InputTokens, OutputTokens                                *int64
	MediaType                                                string
	SizeBytes                                                int64
	SHA256                                                   []byte
	ExpiresAt, CreatedAt, UpdatedAt                          time.Time
	State                                                    TaskMediaStagedObjectState
	CleanupState                                             TaskMediaCleanupState
}

type CreateTaskMediaStagedObjectCommand struct {
	TaskID, OwnerID, OperationID, RuntimeCallID string
	PendingRequestID                            string
	PendingRequestVersion                       int64
	MediaType                                   string
	SizeBytes                                   int64
	SHA256                                      []byte
	ExpiresAt                                   time.Time
}

// TaskMediaApprovalCommit atomically completes a generated Task operation,
// inserts its staged metadata, and links the exact pending approval.
type TaskMediaApprovalCommit struct {
	OperationID, RuntimeCallID, ProviderOperationID string
	OperationResult                                 string
	MediaType                                       string
	SizeBytes                                       int64
	SHA256                                          []byte
	ExpiresAt                                       time.Time
}

// TaskMediaStagedObjectStore persists metadata while generic Task operations
// and model_call_ledger remain the source of provider operation and Token state.
// CreateTaskMediaPreviewForApproval must atomically persist the object and link
// it to the exact still-pending approval identified in the command.
type TaskMediaStagedObjectStore interface {
	CreateTaskMediaPreviewForApproval(context.Context, CreateTaskMediaStagedObjectCommand) error
	GetTaskMediaOperationDetails(context.Context, string, string) (TaskMediaStagedObject, error)
	GetTaskMediaPreviewForOwner(context.Context, string, string, string, time.Time) (TaskMediaStagedObject, error)
	// Expired previews must be CAS-transitioned to expired before deleting bytes so approval cannot start saving concurrently.
	// Complete rows are returned for metadata-delete retries; callers skip deleting bytes again for those rows.
	ListTaskMediaObjectsForCleanup(context.Context, time.Time, int32) ([]TaskMediaStagedObject, error)
	CanCleanupTaskMediaStagedObject(context.Context, string, string) (bool, error)
	ExpireTaskMediaPreviewApproval(context.Context, string, string) error
	SetTaskMediaStagedObjectState(context.Context, string, string, TaskMediaStagedObjectState, TaskMediaStagedObjectState) (TaskMediaStagedObject, error)
	MarkTaskMediaStagedObjectCleanupComplete(context.Context, string, string) error
	DeleteCleanedTaskMediaStagedObject(context.Context, string, string) error
}

type TaskMediaStagedContent struct {
	MediaType string
	SizeBytes int64
	SHA256    []byte
}

// TaskMediaContentStore keeps generated bytes outside the database and derives
// every private path from validated owner, Task, and operation identifiers.
type TaskMediaContentStore interface {
	Stage(context.Context, string, string, string, string, io.Reader) (TaskMediaStagedContent, error)
	Open(context.Context, string, string, string) (io.ReadCloser, error)
	Delete(context.Context, string, string, string) error
}

type TaskMediaVerifiedContentStore interface {
	OpenVerified(context.Context, string, string, string, TaskMediaStagedContent) (io.ReadCloser, error)
}

// TaskMediaApprovedSaveStore only returns staged bytes bound to the exact
// approved request while its Task is queued or running.
type TaskMediaApprovedSaveStore interface {
	GetTaskMediaForApprovedSave(context.Context, string, string, string, int64, string) (TaskMediaStagedObject, error)
}

type TaskMediaSaveInput struct {
	Body      io.ReadCloser
	MediaType string
	SizeBytes int64
	SHA256    []byte
}

type TaskMediaSavedArtifact struct {
	Path      string
	Revision  int64
	MediaType string
	SizeBytes int64
	SHA256    string
}
