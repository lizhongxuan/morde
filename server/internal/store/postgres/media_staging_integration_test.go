func TestTaskMediaStagedObjectLinksPendingApprovalAndSettledLedger(t *testing.T) {
	store, _ := newTemporaryStore(t)
	ctx := context.Background()
	hostValue, _, _, taskValue, publish := newTaskWorkspacePublishTask(t, ctx, store, "media-staging")
	if _, err := store.pool.Exec(ctx, `UPDATE tasks SET status='waiting_user', lease_owner='', lease_expires_at=NULL WHERE id=$1`, taskValue.ID); err != nil {
		t.Fatal(err)
	}
	pendingID, err := domain.NewPendingRequestID()
	if err != nil {
		t.Fatal(err)
	}
	operationID, err := domain.NewOperationID()
	if err != nil {
		t.Fatal(err)
	}
	requestHash := sha256.Sum256([]byte("media request"))
	callID := "media-call-12345"
	seedTaskMediaOperation(t, ctx, store, hostValue, taskValue.ID, taskValue.OwnerID, publish.LeaseVersion, operationID, callID, requestHash[:], "provider-op-image")
	if _, err := store.pool.Exec(ctx, `INSERT INTO task_pending_requests (
  id, task_id, version, kind, title, object, content, impact, call_id, tool_name, request_hash,
  runtime_generation, runtime_instance_id, control_version, status
) VALUES ($1, $2, 1, 'approval', 'Save generated image', 'Workspace output', 'A generated image is ready',
  'The file will be written to your Workspace', $3, 'media.generate', $4, $5, $6, $7, 'pending')`,
		pendingID, taskValue.ID, callID, requestHash[:], hostValue.RuntimeGeneration, hostValue.RuntimeInstanceID, hostValue.ControlVersion); err != nil {
		t.Fatal(err)
	}
	contentHash := sha256.Sum256([]byte("generated bytes"))
	command := app.CreateTaskMediaStagedObjectCommand{
		TaskID: taskValue.ID, OwnerID: taskValue.OwnerID, OperationID: operationID, RuntimeCallID: callID,
		PendingRequestID: pendingID, PendingRequestVersion: 1, MediaType: "image/png", SizeBytes: int64(len("generated bytes")),
		SHA256: contentHash[:], ExpiresAt: time.Now().UTC().Add(time.Hour),
	}
	if err := store.CreateTaskMediaPreviewForApproval(ctx, command); err != nil {
		t.Fatalf("CreateTaskMediaPreviewForApproval() error = %v", err)
	}
	preview, err := store.GetTaskMediaPreviewForOwner(ctx, taskValue.OwnerID, taskValue.ID, operationID, time.Now().UTC())
	if err != nil {
		t.Fatalf("GetTaskMediaPreviewForOwner() error = %v", err)
	}
	if preview.ProviderOperationID != "provider-op-image" || preview.TokenState != "settled" || preview.ReservedTokens != 100 ||
		preview.InputTokens == nil || *preview.InputTokens != 8 || preview.OutputTokens == nil || *preview.OutputTokens != 3 ||
		preview.State != app.TaskMediaPreviewPending || preview.SizeBytes != command.SizeBytes {
		t.Fatalf("preview operation details = %#v", preview)
	}
	if _, err := store.GetTaskMediaPreviewForOwner(ctx, "u9999999", taskValue.ID, operationID, time.Now().UTC()); domain.CodeOf(err) != domain.CodeNotFound {
		t.Fatalf("other owner preview error = %v, want not found", err)
	}
	if objects, err := store.ListTaskMediaObjectsForCleanup(ctx, time.Now().UTC(), 10); err != nil || len(objects) != 0 {
		t.Fatalf("pending preview cleanup list = %#v, %v", objects, err)
	}
	if err := store.MarkTaskMediaStagedObjectCleanupComplete(ctx, taskValue.ID, operationID); domain.CodeOf(err) != domain.CodeConflict {
		t.Fatalf("cleanup of pending preview = %v, want conflict", err)
	}
	if _, err := store.SetTaskMediaStagedObjectState(ctx, taskValue.ID, operationID, app.TaskMediaPreviewPending, app.TaskMediaPreviewSaving); err != nil {
		t.Fatalf("transition preview to saving: %v", err)
	}
	if err := store.MarkTaskMediaStagedObjectCleanupComplete(ctx, taskValue.ID, operationID); domain.CodeOf(err) != domain.CodeConflict {
		t.Fatalf("cleanup of active media save = %v, want conflict", err)
	}
	if objects, err := store.ListTaskMediaObjectsForCleanup(ctx, time.Now().UTC(), 10); err != nil || len(objects) != 0 {
		t.Fatalf("active save appeared in cleanup list: %#v, %v", objects, err)
	}
	if _, err := store.SetTaskMediaStagedObjectState(ctx, taskValue.ID, operationID, app.TaskMediaPreviewSaving, app.TaskMediaPreviewSaved); err != nil {
		t.Fatalf("transition saving to published: %v", err)
	}
	objects, err := store.ListTaskMediaObjectsForCleanup(ctx, time.Now().UTC(), 10)
	if err != nil || len(objects) != 1 || objects[0].OperationID != operationID {
		t.Fatalf("published media cleanup list = %#v, %v", objects, err)
	}
	if err := store.MarkTaskMediaStagedObjectCleanupComplete(ctx, taskValue.ID, operationID); err != nil {
		t.Fatalf("mark media cleanup complete: %v", err)
	}
	if err := store.MarkTaskMediaStagedObjectCleanupComplete(ctx, taskValue.ID, operationID); err != nil {
		t.Fatalf("repeat media cleanup completion: %v", err)
	}
	cleanup, err := store.ListTaskMediaObjectsForCleanup(ctx, time.Now().UTC(), 10)
	if err != nil || len(cleanup) != 1 || cleanup[0].CleanupState != app.TaskMediaCleanupComplete {
		t.Fatalf("completed media cleanup retry = %#v, %v", cleanup, err)
	}
	if err := store.DeleteCleanedTaskMediaStagedObject(ctx, taskValue.ID, operationID); err != nil {
		t.Fatalf("delete cleaned media record: %v", err)
	}
	var linkedOperation string
	if err := store.pool.QueryRow(ctx, `SELECT COALESCE(media_preview_operation_id, '') FROM task_pending_requests WHERE id=$1`, pendingID).Scan(&linkedOperation); err != nil || linkedOperation != "" {
		t.Fatalf("pending request preview after cleanup = %q, %v", linkedOperation, err)
	}
	if _, err := store.GetTaskMediaOperationDetails(ctx, taskValue.ID, operationID); domain.CodeOf(err) != domain.CodeNotFound {
		t.Fatalf("deleted media metadata lookup error = %v, want not found", err)
	}
	failedOperationID, err := domain.NewOperationID()
	if err != nil {
		t.Fatal(err)
	}
	failedCallID := "media-call-67890"
	failedHash := sha256.Sum256([]byte("late media request"))
	seedTaskMediaOperation(t, ctx, store, hostValue, taskValue.ID, taskValue.OwnerID, publish.LeaseVersion, failedOperationID, failedCallID, failedHash[:], "provider-op-late")
	if _, err := store.pool.Exec(ctx, `UPDATE task_pending_requests SET status='approved', decision='approve', responded_at=clock_timestamp() WHERE id=$1`, pendingID); err != nil {
		t.Fatal(err)
	}
	command.OperationID = failedOperationID
	command.RuntimeCallID = failedCallID
	command.PendingRequestID = pendingID
	command.SHA256 = failedHash[:]
	if err := store.CreateTaskMediaPreviewForApproval(ctx, command); domain.CodeOf(err) != domain.CodeConflict {
		t.Fatalf("link to decided approval error = %v, want conflict", err)
	}
	var failedRows int64
	if err := store.pool.QueryRow(ctx, `SELECT count(*) FROM task_media_staged_objects WHERE operation_id=$1`, failedOperationID).Scan(&failedRows); err != nil || failedRows != 0 {
		t.Fatalf("rolled back staged media rows = %d, %v", failedRows, err)
	}
}

func seedTaskMediaOperation(t *testing.T, ctx context.Context, store *Store, hostValue host.Host, taskID, ownerID string, leaseVersion int64, operationID, callID string, requestHash []byte, providerOperationID string) {
	t.Helper()
	if _, err := store.pool.Exec(ctx, `INSERT INTO task_operations (
  id, task_id, operation_key, request_hash, host_id, runtime_generation, control_version, lease_version, status, external_id
) VALUES ($1, $2, $3, $4, $5, $6, $7, $8, 'succeeded', $9)`, operationID, taskID, "media:"+operationID, requestHash,
		hostValue.ID, hostValue.RuntimeGeneration, hostValue.ControlVersion, leaseVersion, providerOperationID); err != nil {
		t.Fatal(err)
	}
	if _, err := store.pool.Exec(ctx, `INSERT INTO model_call_ledger (
  owner_id, source, call_id, request_digest, model_id, provider_model, task_id, reserved_tokens,
  state, input_tokens, output_tokens, created_at, settled_at
) VALUES ($1, 'task', $2, $3, 'p1234567', 'media-model', $4, 100, 'settled', 8, 3, clock_timestamp(), clock_timestamp())`,
		ownerID, callID, requestHash, taskID); err != nil {
		t.Fatal(err)
	}
}

func TestTaskMediaStagedObjectUsesProjectInitiatorForTokenLedger(t *testing.T) {
	store, _ := newTemporaryStore(t)
	ctx := context.Background()
	projectOwner := createPreRetirementTestUser(t, store, 4, 20_000, 40_000)
	conversationOwner := createPreRetirementTestUser(t, store, 4, 20_000, 40_000)
	initiator := createPreRetirementTestUser(t, store, 4, 20_000, 40_000)
	projectValue := createProjectStoreFixture(t, ctx, store, projectOwner.ID, "Shared media", "Project media accounting", "project-media-create")
	if _, err := inviteAndAcceptProjectStoreMember(t, ctx, store, projectOwner.ID, conversationOwner.ID, projectValue,
		project.RoleMember, projectValue.Version, "project-media-conversation-invite", "project-media-conversation-accept"); err != nil {
		t.Fatal(err)
	}
	currentProject, err := store.GetProject(ctx, projectOwner.ID, projectValue.ID)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := inviteAndAcceptProjectStoreMember(t, ctx, store, projectOwner.ID, initiator.ID, projectValue,
		project.RoleMember, currentProject.Version, "project-media-initiator-invite", "project-media-initiator-accept"); err != nil {
		t.Fatal(err)
	}
	conversationID := mustID(t, domain.NewConversationID)
	sharedConversation, replayed, err := store.CreateProjectConversation(ctx, conversationOwner.ID, conversation.Conversation{
		ID: conversationID, OwnerID: conversationOwner.ID, ProjectID: projectValue.ID, Title: "Project media accounting",
	}, testIdempotency(conversationOwner.ID, "project_conversation.create", "project-media-conversation"))
	if err != nil || replayed {
		t.Fatalf("create project conversation: replayed=%t err=%v", replayed, err)
	}
	hostValue := createRunningControlHost(t, ctx, store, initiator.ID, host.ControlAI, 0)
	submission := newTestTaskSubmission(t, conversationOwner.ID, hostValue.ID, "project-media-task-message", "generate media")
	submission.Task.ProjectID = projectValue.ID
	submission.Task.InitiatorID = initiator.ID
	submission.Task.ConversationID = sharedConversation.ID
	submission.Task.ExecutionLocation = "server"
	submission.Task.Authorization.TokenID = testSessionTokenID(initiator.ID)
	submission.Message.ConversationID = sharedConversation.ID
	submission.Message.ActorID = initiator.ID
	submission.Idempotency = testIdempotency(initiator.ID, "task.submit", "project-media-task-message")
	created, err := store.SubmitTask(ctx, submission)
	if err != nil {
		t.Fatalf("submit Project Task as member: %v", err)
	}
	if created.Task.OwnerID != conversationOwner.ID || created.Task.InitiatorID != initiator.ID {
		t.Fatalf("Project Task owner/initiator = %q/%q", created.Task.OwnerID, created.Task.InitiatorID)
	}
	if _, err := store.pool.Exec(ctx, `UPDATE tasks SET status='waiting_user', waiting_reason='approval_required' WHERE id=$1`, created.Task.ID); err != nil {
		t.Fatal(err)
	}
	const operationID = "o6123456"
	const pendingID = "r6123456"
	const callID = "project-media-call-612"
	requestHash := sha256.Sum256([]byte("project media request"))
	seedTaskMediaOperation(t, ctx, store, hostValue, created.Task.ID, initiator.ID, 1, operationID, callID, requestHash[:], "provider-op-project-image")
	if _, err := store.pool.Exec(ctx, `INSERT INTO task_pending_requests (
  id, task_id, version, kind, title, object, content, impact, call_id, tool_name, request_hash,
  runtime_generation, runtime_instance_id, control_version, status
) VALUES ($1,$2,1,'approval','Save generated media','Workspace output','Review generated image',
  'The file will be written to the Task Workspace',$3,'image.generate',$4,$5,$6,$7,'pending')`,
		pendingID, created.Task.ID, callID, requestHash[:], hostValue.RuntimeGeneration, hostValue.RuntimeInstanceID, hostValue.ControlVersion); err != nil {
		t.Fatal(err)
	}
	content := []byte("project generated media")
	contentHash := sha256.Sum256(content)
	if err := store.CreateTaskMediaPreviewForApproval(ctx, app.CreateTaskMediaStagedObjectCommand{
		TaskID: created.Task.ID, OwnerID: conversationOwner.ID, OperationID: operationID, RuntimeCallID: callID,
		PendingRequestID: pendingID, PendingRequestVersion: 1, MediaType: "image/png", SizeBytes: int64(len(content)),
		SHA256: contentHash[:], ExpiresAt: time.Now().UTC().Add(time.Hour),
	}); err != nil {
		t.Fatalf("stage Project Task media preview: %v", err)
	}
	preview, err := store.GetTaskMediaPreviewForOwner(ctx, conversationOwner.ID, created.Task.ID, operationID, time.Now().UTC())
	if err != nil {
		t.Fatalf("read Project Task media preview: %v", err)
	}
	if preview.OwnerID != conversationOwner.ID || preview.InitiatorID != initiator.ID || preview.TokenState != "settled" {
		t.Fatalf("Project Task preview owner/initiator/ledger = %q/%q/%q", preview.OwnerID, preview.InitiatorID, preview.TokenState)
	}
}

func TestTaskMediaValidationRejectsInvalidStateTransitions(t *testing.T) {
	store, _ := newTemporaryStore(t)
	ctx := context.Background()
	if _, err := store.SetTaskMediaStagedObjectState(ctx, "q1234567", "o1234567", app.TaskMediaStagedObjectState("other"), app.TaskMediaPreviewSaving); domain.CodeOf(err) != domain.CodeInvalidArgument {
		t.Fatalf("invalid media state transition error = %v", err)
	}
	if _, err := store.GetTaskMediaPreviewForOwner(ctx, "u1234567", "q1234567", "o1234567", time.Time{}); domain.CodeOf(err) != domain.CodeInvalidArgument {
		t.Fatalf("zero-time preview query error = %v", err)
	}
	if _, err := store.ListTaskMediaObjectsForCleanup(ctx, time.Now(), 0); domain.CodeOf(err) != domain.CodeInvalidArgument {
		t.Fatalf("invalid cleanup batch error = %v", err)
	}
	if err := store.CreateTaskMediaPreviewForApproval(ctx, app.CreateTaskMediaStagedObjectCommand{}); domain.CodeOf(err) != domain.CodeInvalidArgument {
		t.Fatalf("invalid media staging command error = %v", err)
	}
	if _, err := store.GetTaskMediaOperationDetails(ctx, "q1234567", "o1234567"); domain.CodeOf(err) != domain.CodeNotFound {
		t.Fatalf("missing media operation error = %v", err)
	}
}

func TestTaskMediaStateTransitionsAreOneWay(t *testing.T) {
	for _, transition := range []struct {
		from, to app.TaskMediaStagedObjectState
		want     bool
	}{
		{app.TaskMediaPreviewPending, app.TaskMediaPreviewSaving, true},
		{app.TaskMediaPreviewPending, app.TaskMediaPreviewDiscard, true},
		{app.TaskMediaPreviewPending, app.TaskMediaPreviewExpired, true},
		{app.TaskMediaPreviewSaving, app.TaskMediaPreviewSaved, true},
		{app.TaskMediaPreviewSaving, app.TaskMediaPreviewDiscard, true},
		{app.TaskMediaPreviewSaving, app.TaskMediaPreviewExpired, true},
		{app.TaskMediaPreviewSaved, app.TaskMediaPreviewPending, false},
		{app.TaskMediaPreviewDiscard, app.TaskMediaPreviewSaving, false},
		{app.TaskMediaPreviewExpired, app.TaskMediaPreviewPending, false},
	} {
		if got := validTaskMediaTransition(transition.from, transition.to); got != transition.want {
			t.Errorf("validTaskMediaTransition(%q, %q) = %t, want %t", transition.from, transition.to, got, transition.want)
		}
	}
}
